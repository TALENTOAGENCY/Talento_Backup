// Helper functions for scalable query and filtering
export function getAllInsights(): InsightEntity[] {
  return insightsData;
}

export function getInsightBySlug(slug: string): InsightEntity | undefined {
  if (!slug) return undefined;
  const normalized = slug.toLowerCase().trim();
  return insightsData.find((item) => item.slug === normalized);
}

export function getInsightsByCategory(category: string): InsightEntity[] {
  if (!category || category === 'All') return insightsData;
  return insightsData.filter((item) => item.category === category);
}

export function getRelatedInsights(currentSlug: string, category?: string, limit = 3): InsightEntity[] {
  return insightsData
    .filter((item) => item.slug !== currentSlug)
    .sort((a, b) => {
      // Prioritize same category
      if (category && a.category === category && b.category !== category) return -1;
      if (category && b.category === category && a.category !== category) return 1;
      return new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime();
    })
    .slice(0, limit);
}
