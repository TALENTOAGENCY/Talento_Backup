// Helper Functions for Case Studies

export function getAllCaseStudies(): CaseStudyEntity[] {
  return caseStudiesData;
}

export function getCaseStudyBySlug(slug: string): CaseStudyEntity | undefined {
  return caseStudiesData.find((item) => item.slug === slug);
}

export function getCaseStudiesByIndustry(industrySlug: string): CaseStudyEntity[] {
  return caseStudiesData.filter(
    (item) => item.industrySlug === industrySlug || item.relatedIndustries?.includes(industrySlug)
  );
}

export function getCaseStudiesByService(serviceSlug: string): CaseStudyEntity[] {
  return caseStudiesData.filter((item) => item.relatedServices?.includes(serviceSlug));
}
